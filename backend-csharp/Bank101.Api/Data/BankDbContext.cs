using Bank101.Api.Models;
using Microsoft.EntityFrameworkCore;

namespace Bank101.Api.Data;

public class BankDbContext(DbContextOptions<BankDbContext> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<Account> Accounts => Set<Account>();
    public DbSet<Transaction> Transactions => Set<Transaction>();
    public DbSet<Invoice> Invoices => Set<Invoice>();
    public DbSet<Payment> Payments => Set<Payment>();
    public DbSet<AuditLog> AuditLogs => Set<AuditLog>();

    /// <summary>
    /// "Now" for timestamp columns. The schema uses `timestamp without time zone`
    /// (Alembic/SQLAlchemy `DateTime`), and Npgsql refuses to write a DateTime with
    /// Kind=Utc into that type — so the Kind is stripped, matching what the Python
    /// side stores via datetime.utcnow().
    /// </summary>
    public static DateTime UtcNowNaive() =>
        DateTime.SpecifyKind(DateTime.UtcNow, DateTimeKind.Unspecified);

    protected override void OnModelCreating(ModelBuilder b)
    {
        // Alembic created the primary keys as SERIAL; EF Core would otherwise emit
        // `GENERATED BY DEFAULT AS IDENTITY`. Both auto-increment, but matching the
        // existing DDL keeps a fresh EF-built database identical to an Alembic-built
        // one — so the two backends can be pointed at either without surprises.
        b.UseSerialColumns();

        b.Entity<User>(e =>
        {
            e.ToTable("users");
            e.HasKey(x => x.Id).HasName("users_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.Email).HasColumnName("email").HasMaxLength(254).IsRequired();
            e.Property(x => x.Username).HasColumnName("username").HasMaxLength(30).IsRequired();
            e.Property(x => x.FullName).HasColumnName("full_name").HasMaxLength(120).IsRequired();
            e.Property(x => x.DateOfBirth).HasColumnName("date_of_birth").IsRequired();
            e.Property(x => x.Address).HasColumnName("address").HasMaxLength(255).IsRequired();
            e.Property(x => x.PhoneNumber).HasColumnName("phone_number").HasMaxLength(20).IsRequired();
            e.Property(x => x.HashedPassword).HasColumnName("hashed_password").HasMaxLength(255).IsRequired();
            e.Property(x => x.Role).HasColumnName("role").HasMaxLength(30).IsRequired();
            e.Property(x => x.IsActive).HasColumnName("is_active").IsRequired();
            e.Property(x => x.KycStatus).HasColumnName("kyc_status").HasMaxLength(30).IsRequired();
            e.Property(x => x.AmlStatus).HasColumnName("aml_status").HasMaxLength(30).IsRequired();
            e.Property(x => x.RiskLevel).HasColumnName("risk_level").HasMaxLength(20).IsRequired();
            e.Property(x => x.KycVerifiedAt).HasColumnName("kyc_verified_at");
            e.Property(x => x.KycProvider).HasColumnName("kyc_provider").HasMaxLength(100);
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at").IsRequired().HasDefaultValueSql("now()");

            e.HasIndex(x => x.Email).IsUnique().HasDatabaseName("ix_users_email");
            e.HasIndex(x => x.Username).IsUnique().HasDatabaseName("ix_users_username");
        });

        b.Entity<Account>(e =>
        {
            e.ToTable("accounts");
            e.HasKey(x => x.Id).HasName("accounts_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.UserId).HasColumnName("user_id").IsRequired();
            e.Property(x => x.AccountNumber).HasColumnName("account_number").HasMaxLength(20).IsRequired();
            e.Property(x => x.AccountType).HasColumnName("account_type").HasMaxLength(30).IsRequired();
            e.Property(x => x.Balance).HasColumnName("balance").HasPrecision(18, 2).IsRequired();
            e.Property(x => x.Status).HasColumnName("status").HasMaxLength(20).IsRequired();
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at").IsRequired().HasDefaultValueSql("now()");

            e.HasIndex(x => x.UserId).HasDatabaseName("ix_accounts_user_id");
            e.HasIndex(x => x.AccountNumber).IsUnique().HasDatabaseName("ix_accounts_account_number");

            // Matches Alembic revision c9f1a2b3d4e5 (fk_accounts_user_id_users).
            e.HasOne(x => x.User)
                .WithMany(u => u.Accounts)
                .HasForeignKey(x => x.UserId)
                .OnDelete(DeleteBehavior.NoAction)
                .HasConstraintName("fk_accounts_user_id_users");
        });

        b.Entity<Transaction>(e =>
        {
            e.ToTable("transactions");
            e.HasKey(x => x.Id).HasName("transactions_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.AccountId).HasColumnName("account_id").IsRequired();
            e.Property(x => x.TransactionType).HasColumnName("transaction_type").HasMaxLength(30).IsRequired();
            e.Property(x => x.Amount).HasColumnName("amount").HasPrecision(18, 2).IsRequired();
            e.Property(x => x.Status).HasColumnName("status").HasMaxLength(20).IsRequired();
            e.Property(x => x.Description).HasColumnName("description").HasMaxLength(255);
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at").IsRequired().HasDefaultValueSql("now()");

            e.HasOne(x => x.Account)
                .WithMany(a => a.Transactions)
                .HasForeignKey(x => x.AccountId)
                .OnDelete(DeleteBehavior.NoAction)
                .HasConstraintName("transactions_account_id_fkey");
            e.HasIndex(x => x.AccountId).HasDatabaseName("ix_transactions_account_id");
        });

        b.Entity<Invoice>(e =>
        {
            e.ToTable("invoices");
            e.HasKey(x => x.Id).HasName("invoices_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.UserId).HasColumnName("user_id").IsRequired();
            e.Property(x => x.Amount).HasColumnName("amount").HasPrecision(18, 2).IsRequired();
            e.Property(x => x.Status).HasColumnName("status").HasMaxLength(20).IsRequired();
            e.Property(x => x.DueDate).HasColumnName("due_date").IsRequired();
            e.Property(x => x.Description).HasColumnName("description").HasMaxLength(255);
            e.Property(x => x.PaidAt).HasColumnName("paid_at");
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at").IsRequired().HasDefaultValueSql("now()");

            e.HasOne(x => x.User).WithMany().HasForeignKey(x => x.UserId)
                .OnDelete(DeleteBehavior.NoAction).HasConstraintName("invoices_user_id_fkey");
            e.HasIndex(x => x.UserId).HasDatabaseName("ix_invoices_user_id");
        });

        b.Entity<Payment>(e =>
        {
            e.ToTable("payments");
            e.HasKey(x => x.Id).HasName("payments_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.AccountId).HasColumnName("account_id").IsRequired();
            e.Property(x => x.InvoiceId).HasColumnName("invoice_id").IsRequired();
            e.Property(x => x.Amount).HasColumnName("amount").HasPrecision(18, 2).IsRequired();
            e.Property(x => x.Status).HasColumnName("status").HasMaxLength(20).IsRequired();
            e.Property(x => x.Description).HasColumnName("description").HasMaxLength(255);
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.UpdatedAt).HasColumnName("updated_at").IsRequired().HasDefaultValueSql("now()");
            e.Property(x => x.CompletedAt).HasColumnName("completed_at");

            e.HasOne(x => x.Account).WithMany().HasForeignKey(x => x.AccountId)
                .OnDelete(DeleteBehavior.NoAction).HasConstraintName("payments_account_id_fkey");
            e.HasOne(x => x.Invoice).WithMany().HasForeignKey(x => x.InvoiceId)
                .OnDelete(DeleteBehavior.NoAction).HasConstraintName("payments_invoice_id_fkey");
            e.HasIndex(x => x.AccountId).HasDatabaseName("ix_payments_account_id");
            e.HasIndex(x => x.InvoiceId).HasDatabaseName("ix_payments_invoice_id");
        });

        b.Entity<AuditLog>(e =>
        {
            e.ToTable("audit_logs");
            e.HasKey(x => x.Id).HasName("audit_logs_pkey");
            e.Property(x => x.Id).HasColumnName("id");
            e.Property(x => x.UserId).HasColumnName("user_id").IsRequired();
            e.Property(x => x.Action).HasColumnName("action").HasMaxLength(100).IsRequired();
            e.Property(x => x.EntityType).HasColumnName("entity_type").HasMaxLength(50).IsRequired();
            e.Property(x => x.EntityId).HasColumnName("entity_id").IsRequired();
            e.Property(x => x.Source).HasColumnName("source").HasMaxLength(50).IsRequired();
            e.Property(x => x.UserAgent).HasColumnName("user_agent").HasMaxLength(255);
            e.Property(x => x.Details).HasColumnName("details").HasMaxLength(255);
            e.Property(x => x.CreatedAt).HasColumnName("created_at").IsRequired().HasDefaultValueSql("now()");

            e.HasOne(x => x.User).WithMany().HasForeignKey(x => x.UserId)
                .OnDelete(DeleteBehavior.NoAction).HasConstraintName("audit_logs_user_id_fkey");
            e.HasIndex(x => x.UserId).HasDatabaseName("ix_audit_logs_user_id");
        });

        // Npgsql maps DateTime to `timestamp with time zone` by default and then
        // demands Kind=Utc, but every timestamp column Alembic created is
        // `timestamp without time zone` (SQLAlchemy's plain DateTime). Pinning the
        // column type here keeps EF aligned with the real schema and lets the naive
        // values from UtcNowNaive() write cleanly.
        foreach (var entityType in b.Model.GetEntityTypes())
        {
            foreach (var property in entityType.GetProperties())
            {
                if (property.ClrType == typeof(DateTime) || property.ClrType == typeof(DateTime?))
                    property.SetColumnType("timestamp without time zone");
            }
        }
    }

    public override int SaveChanges()
    {
        StampTimestamps();
        return base.SaveChanges();
    }

    public override Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        StampTimestamps();
        return base.SaveChangesAsync(cancellationToken);
    }

    /// <summary>
    /// EF has no equivalent of SQLAlchemy's server_default/onupdate=func.now(), so
    /// created_at/updated_at are stamped here instead. Entities that already carry an
    /// explicit created_at (e.g. backdated demo transactions) keep theirs.
    /// </summary>
    private void StampTimestamps()
    {
        var now = UtcNowNaive();

        foreach (var entry in ChangeTracker.Entries())
        {
            if (entry.State is not (EntityState.Added or EntityState.Modified)) continue;

            if (entry.State == EntityState.Added
                && entry.Metadata.FindProperty("CreatedAt") is not null
                && entry.CurrentValues["CreatedAt"] is DateTime created
                && created == default)
            {
                entry.CurrentValues["CreatedAt"] = now;
            }

            if (entry.Metadata.FindProperty("UpdatedAt") is not null)
            {
                entry.CurrentValues["UpdatedAt"] = now;
            }
        }
    }
}
